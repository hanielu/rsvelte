//! Upstream `Binding.ts` pushes a binding's name as a source range —
//! `[attr.start, …]` for an element's `"bind:value"` key, `[attr.start +
//! 'bind:'.length, …]` for a component's `value` prop — so hover and
//! diagnostics on the directive name reach the property it becomes. Baked into
//! a literal, the name had no mapping of its own and a hover on it answered
//! for whatever chunk sat nearest (the component, for a component binding).

use rsvelte_projection::svelte2tsx::{Svelte2TsxOptions, svelte2tsx};

const SOURCE: &str = r#"<script lang="ts">
  import Widget from "./Widget.svelte";
  let name = $state("x");
  let on = $state(true);
</script>

<input bind:value={name} />
<Widget bind:open={on} label="x" />
"#;

fn project(source: &str) -> (String, sourcemap::SourceMap) {
    let result = svelte2tsx(
        source,
        Svelte2TsxOptions {
            filename: "A.svelte".to_string(),
            is_ts_file: true,
            ..Default::default()
        },
    )
    .expect("svelte2tsx");
    let map = sourcemap::SourceMap::from_slice(result.map.as_deref().expect("map").as_bytes())
        .expect("valid source map");
    (result.code, map)
}

/// The source `(line, column)` the generated byte at `offset` maps to.
fn source_of(code: &str, map: &sourcemap::SourceMap, offset: usize) -> (u32, u32) {
    let before = &code[..offset];
    let line = before.matches('\n').count() as u32;
    let column = (offset - before.rfind('\n').map_or(0, |newline| newline + 1)) as u32;
    let token = map.lookup_token(line, column).expect("a mapping");
    (token.get_src_line(), token.get_src_col())
}

/// The `(line, column)` of `needle` in the source, plus `delta`.
fn source_position(needle: &str, delta: u32) -> (u32, u32) {
    let (line, text) = SOURCE
        .lines()
        .enumerate()
        .find(|(_, text)| text.contains(needle))
        .expect("source line");
    (
        line as u32,
        text.find(needle).expect("needle") as u32 + delta,
    )
}

#[test]
fn an_element_binding_key_maps_to_the_directive_name() {
    let (code, map) = project(SOURCE);
    let key = code
        .find("\"bind:value\":name")
        .expect("element binding key")
        + 1;
    // Each character of `bind:value`, including the `value` a hover lands on.
    for delta in 0.."bind:value".len() as u32 {
        assert_eq!(
            source_of(&code, &map, key + delta as usize),
            source_position("bind:value", delta),
            "generated `bind:value` + {delta}"
        );
    }
}

#[test]
fn a_component_binding_prop_maps_to_the_directive_name() {
    let (code, map) = project(SOURCE);
    let key = code.find("open:on,").expect("component binding prop");
    for delta in 0.."open".len() as u32 {
        assert_eq!(
            source_of(&code, &map, key + delta as usize),
            source_position("bind:open", "bind:".len() as u32 + delta),
            "generated `open` + {delta}"
        );
    }
}

#[test]
fn the_generated_bindings_are_unchanged() {
    let (code, _) = project(SOURCE);
    assert!(code.contains(" \"bind:value\":name,});"), "{code}");
    assert!(code.contains(" open:on,\"label\":`x`,}"), "{code}");
    // A shorthand binding is the bound expression itself.
    let (shorthand, _) = project("<script>let open = true;</script>\n<Widget bind:open />\n");
    assert!(shorthand.contains(" open,}"), "{shorthand}");
}

/// A shorthand element binding's name is its expression's text, which keeps
/// the mapping (upstream writes that key as a literal): `files` in
/// `bind:files` still maps to the bound variable.
#[test]
fn a_shorthand_element_binding_keeps_its_expression_mapping() {
    let source = "<script lang=\"ts\">\n  let files: FileList | undefined = $state();\n</script>\n\n<input type=\"file\" bind:files />\n";
    let (code, map) = project(source);
    let value = code
        .find("\"bind:files\":files")
        .expect("shorthand binding")
        + "\"bind:files\":".len();
    let line = source
        .lines()
        .position(|line| line.starts_with("<input"))
        .unwrap() as u32;
    let column = source
        .lines()
        .nth(line as usize)
        .unwrap()
        .find("files")
        .unwrap() as u32;
    for delta in 0.."files".len() as u32 {
        assert_eq!(
            source_of(&code, &map, value + delta as usize),
            (line, column + delta),
            "generated `files` + {delta}"
        );
    }
}
